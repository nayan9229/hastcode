#!/usr/bin/env bash
# Checks the signup Worker (worker/index.js) by hand: starts a stub
# Buttondown, runs the Worker under `wrangler dev` with the built static
# tree as its assets, and curls every case the Go subscribe tests cover
# (subscribe/subscribe_test.go), printing PASS/FAIL per case. Exit status is
# the number of failed cases (0 = all passed).
#
#   scripts/check-worker.sh [ASSETS_DIR]     # default .vercel/output/static
#
# ASSETS_DIR missing: the script runs `make build MODE=preview
# FLAGS=-skip-search-index` first. Needs bash, curl, node and the pinned
# wrangler from package.json (`npm ci`). No Cloudflare login, no network:
# wrangler dev runs workerd locally and the Worker only talks to the stub.
#
# Tests stay Go-only (spec "Testing Decisions"): this script is a manual
# check, not part of `make test`. The same cases belong on the first-Preview
# checklist in the setup wizard (scripts/setup-deploy.sh).
#
# The Workers config here is a throwaway written to a temp dir; the real one
# is generated by the builder (Cloudflare manifest). Ports: STUB_PORT
# (default 18790) and WORKER_PORT (default 18791, plus one for the
# missing-key instance).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

assets="${1:-${ASSETS_DIR:-.vercel/output/static}}"
stub_port="${STUB_PORT:-18790}"
worker_port="${WORKER_PORT:-18791}"
nokey_port=$((worker_port + 1))
key="check-worker-key-$RANDOM$RANDOM-0123456789"

if [[ ! -f "$assets/index.html" ]]; then
  echo "no $assets/index.html: building (preview mode)" >&2
  make build MODE=preview FLAGS=-skip-search-index >&2
fi
assets="$(cd "$assets" && pwd)"
[[ -f "$assets/404.html" ]] || { echo "no 404.html in $assets" >&2; exit 1; }
[[ -x node_modules/.bin/wrangler ]] || { echo "wrangler not installed: run npm ci" >&2; exit 1; }

tmp="$(mktemp -d "${TMPDIR:-/tmp}/check-worker.XXXXXX")"
pids=()
cleanup() {
  for p in "${pids[@]}"; do kill "$p" 2>/dev/null || true; done
  wait 2>/dev/null || true
  rm -rf "$tmp"
}
trap cleanup EXIT

# --- stub Buttondown -------------------------------------------------------
# Records every subscriber request as one line in $tmp/stub.log:
#   POST /v1/subscribers auth=<Authorization> email=<..> tags=<json> ip=<..>
# and answers with the current mode, set by POST /_stub/mode
# {"status":503,"body":"..."} or {"drop":true} (close the socket).
cat >"$tmp/stub.mjs" <<'JS'
import http from "node:http";
import fs from "node:fs";
const [port, logFile] = process.argv.slice(2);
let mode = { status: 201, body: '{"id":"sub_1"}' };
fs.writeFileSync(logFile, "");
http.createServer((req, res) => {
  let data = "";
  req.on("data", (c) => (data += c));
  req.on("end", () => {
    if (req.url === "/_stub/mode") {
      mode = JSON.parse(data);
      res.end("ok\n");
      return;
    }
    let sub = {};
    try { sub = JSON.parse(data); } catch {}
    fs.appendFileSync(logFile,
      `${req.method} ${req.url} auth=${req.headers.authorization ?? ""} email=${sub.email_address ?? ""} tags=${JSON.stringify(sub.tags ?? null)} ip=${sub.ip_address ?? ""}\n`);
    if (mode.drop) { req.socket.destroy(); return; }
    res.writeHead(mode.status, { "Content-Type": "application/json" });
    res.end(mode.body);
  });
}).listen(Number(port), "127.0.0.1");
JS
node "$tmp/stub.mjs" "$stub_port" "$tmp/stub.log" &
pids+=($!)

stub_mode() { curl -sS -o /dev/null -X POST --data "$1" "http://127.0.0.1:$stub_port/_stub/mode"; }
stub_reset() { : >"$tmp/stub.log"; stub_mode '{"status":201,"body":"{\"id\":\"sub_1\"}"}'; }
stub_count() { wc -l <"$tmp/stub.log" | tr -d ' '; }

# --- wrangler dev ----------------------------------------------------------
# Same assets settings the Cloudflare manifest declares (spec "One build,
# per-Target manifests").
start_worker() { # name port [--var ...]
  local name="$1" port="$2"; shift 2
  mkdir -p "$tmp/$name"
  cat >"$tmp/$name/wrangler.jsonc" <<JSON
{
  "name": "hastcode-check-$name",
  "main": "$root/worker/index.js",
  "compatibility_date": "2026-10-01",
  "assets": {
    "directory": "$assets",
    "binding": "ASSETS",
    "html_handling": "force-trailing-slash",
    "not_found_handling": "404-page",
    "run_worker_first": ["/api/subscribe"]
  }
}
JSON
  WRANGLER_SEND_METRICS=false WRANGLER_LOG_PATH="$tmp/$name/logs" \
    node_modules/.bin/wrangler dev --config "$tmp/$name/wrangler.jsonc" \
    --ip 127.0.0.1 --port "$port" --show-interactive-dev-session=false \
    --persist-to "$tmp/$name/state" "$@" >"$tmp/$name/out.log" 2>&1 &
  pids+=($!)
  for _ in $(seq 1 120); do
    if curl -s -o /dev/null "http://127.0.0.1:$port/"; then return 0; fi
    sleep 0.5
  done
  echo "wrangler dev ($name) did not start:" >&2
  cat "$tmp/$name/out.log" >&2
  exit 1
}

start_worker main "$worker_port" \
  --var "BUTTONDOWN_API_KEY:$key" --var "BUTTONDOWN_BASE_URL:http://127.0.0.1:$stub_port"
start_worker nokey "$nokey_port" --var "BUTTONDOWN_BASE_URL:http://127.0.0.1:$stub_port"

# --- requests and assertions -----------------------------------------------
base="http://127.0.0.1:$worker_port"
: >"$tmp/all-responses"
status="" headers="" body=""

# req METHOD PATH [curl args...]: sets $status, $headers, $body.
req() {
  local method="$1" path="$2"; shift 2
  status="$(curl -sS -X "$method" -o "$tmp/body" -D "$tmp/headers" -w '%{http_code}' "$@" "${base}${path}")"
  headers="$(cat "$tmp/headers")"
  body="$(cat "$tmp/body")"
  printf '%s\n%s\n' "$headers" "$body" >>"$tmp/all-responses"
}

# post IP ACCEPT EMAIL SOURCE [HONEYPOT]: a form post as the newsletter form
# (ACCEPT=json for its script, form for a no-JS post) from client IP.
post() {
  local ip="$1" accept="$2" email="$3" source="$4" honeypot="${5:-}"
  local a="text/html,application/xhtml+xml,*/*;q=0.8"
  [[ "$accept" == json ]] && a="application/json"
  req POST /api/subscribe -H "Accept: $a" -H "CF-Connecting-IP: $ip" \
    --data-urlencode "email=$email" --data-urlencode "source=$source" --data-urlencode "website=$honeypot"
}

header() { printf '%s\n' "$headers" | tr -d '\r' | sed -n "s/^$1: //Ip" | head -1; }

case_errors=()
expect() { # description, then a test command
  local what="$1"; shift
  if ! "$@"; then case_errors+=("$what (status $status, body $(printf '%s' "$body" | head -c 160))"); fi
}
is() { [[ "$1" == "$2" ]]; }
has() { [[ "$1" == *"$2"* ]]; }
hasnt() { [[ "$1" != *"$2"* ]]; }

passed=0 failed=0
run_case() { # name function
  case_errors=()
  stub_reset
  "$2"
  if ((${#case_errors[@]} == 0)); then
    printf 'PASS  %s\n' "$1"; passed=$((passed + 1))
  else
    printf 'FAIL  %s\n' "$1"; failed=$((failed + 1))
    printf '        - %s\n' "${case_errors[@]}"
  fi
}

case_form_303() {
  post 203.0.113.1 form reader@example.com /distributed-systems/raft-leader-election/
  expect "status 303" is "$status" 303
  expect "Location /subscribed/" is "$(header Location)" /subscribed/
  expect "one upstream request" is "$(stub_count)" 1
  local got; got="$(cat "$tmp/stub.log")"
  printf '%s' "$got" >"$tmp/first-upstream"
  expect "upstream POST /v1/subscribers" has "$got" "POST /v1/subscribers "
  expect "Authorization: Token <key>" has "$got" "auth=Token $key "
  expect "email_address" has "$got" "email=reader@example.com "
  expect "tags = [source]" has "$got" 'tags=["/distributed-systems/raft-leader-election/"]'
  expect "ip_address" has "$got" "ip=203.0.113.1"
}

case_json_200() {
  post 203.0.113.2 json reader@example.com /briefs/postgres-18/
  expect "status 200" is "$status" 200
  expect "JSON content type" has "$(header Content-Type)" application/json
  expect '{"ok":true,...}' has "$body" '{"ok":true,"message":"Thanks!'
  expect "upstream tagged with source" has "$(cat "$tmp/stub.log")" 'email=reader@example.com tags=["/briefs/postgres-18/"]'
}

case_bad_email_400() {
  local i=10 email
  for email in "" not-an-email "reader@" "@example.com" "Reader <reader@example.com>" "reader@example" "a b@example.com"; do
    i=$((i + 1))
    post "203.0.113.$i" json "$email" /x/
    expect "[$email] JSON 400" is "$status" 400
    expect "[$email] JSON not ok, 'valid email'" has "$body" '"ok":false,"message":"Please enter a valid email'
    post "203.0.113.$i" form "$email" /x/
    expect "[$email] form 400" is "$status" 400
    expect "[$email] form message" has "$body" "valid email"
    expect "[$email] form links back to source" has "$body" 'href="/x/"'
  done
  expect "no upstream request" is "$(stub_count)" 0
}

case_honeypot() {
  post 203.0.113.30 form bot@example.com /x/ https://spam.example
  expect "form 303" is "$status" 303
  expect "form Location /subscribed/" is "$(header Location)" /subscribed/
  post 203.0.113.30 json bot@example.com /x/ https://spam.example
  expect "JSON 200 ok" has "$status $body" '200 {"ok":true'
  expect "no upstream request" is "$(stub_count)" 0
}

case_rate_limit() {
  local i
  for i in 1 2 3 4 5; do
    post 198.51.100.1 json reader@example.com /x/
    expect "request $i 200" is "$status" 200
  done
  post 198.51.100.1 json reader@example.com /x/
  expect "request 6 JSON 429" is "$status" 429
  expect "request 6 not ok with a message" has "$body" '"ok":false,"message":"Too many'
  expect "Retry-After 600" is "$(header Retry-After)" 600
  post 198.51.100.1 form reader@example.com /x/
  expect "request 7 form 429" is "$status" 429
  expect "request 7 form message" has "$body" "Too many"
  expect "5 upstream requests" is "$(stub_count)" 5
  post 198.51.100.2 json other@example.com /x/
  expect "another IP 200" is "$status" 200
}

case_upstream_5xx() {
  stub_mode "{\"status\":503,\"body\":\"{\\\"detail\\\":\\\"internal trace: key $key\\\"}\"}"
  post 203.0.113.40 json reader@example.com /x/
  expect "JSON 502" is "$status" 502
  expect "JSON not ok, 'try again'" has "$body" '"ok":false,"message":"We couldn'"'"'t reach our newsletter service. Please try again'
  expect "no key in response" hasnt "$headers$body" "$key"
  expect "no upstream body in response" hasnt "$headers$body" "internal trace"
  post 203.0.113.40 form reader@example.com /x/
  expect "form 502" is "$status" 502
  expect "form 'try again'" has "$body" "try again"
  expect "no key in response" hasnt "$headers$body" "$key"
  expect "no upstream body in response" hasnt "$headers$body" "internal trace"
}

case_upstream_unreachable() {
  stub_mode '{"drop":true}'
  post 203.0.113.41 json reader@example.com /x/
  expect "502" is "$status" 502
  expect "no key in response" hasnt "$headers$body" "$key"
}

case_already_subscribed() {
  stub_mode '{"status":400,"body":"{\"code\":\"subscriber_already_exists\",\"detail\":\"A subscriber with this email already exists.\",\"metadata\":{\"subscriber_id\":\"sub_9\"}}"}'
  post 203.0.113.42 json reader@example.com /x/
  expect "JSON 200 ok" has "$status $body" '200 {"ok":true'
  post 203.0.113.42 form reader@example.com /x/
  expect "form 303" is "$status" 303
}

case_upstream_rejects_email() {
  stub_mode '{"status":400,"body":"{\"code\":\"email_invalid\",\"detail\":\"The email address provided is not valid.\",\"metadata\":{\"field\":\"email_address\"}}"}'
  post 203.0.113.43 json reader@mailinator.example /x/
  expect "400" is "$status" 400
  expect "not ok, 'valid email'" has "$body" '"ok":false,"message":"Please enter a valid email'
}

case_get_405() {
  req GET "/api/subscribe?email=reader@example.com"
  expect "405" is "$status" 405
  expect "Allow: POST" is "$(header Allow)" POST
  expect "no upstream request" is "$(stub_count)" 0
}

case_missing_key() {
  local saved="$base"
  base="http://127.0.0.1:$nokey_port"
  post 203.0.113.50 json reader@example.com /x/
  base="$saved"
  expect "502" is "$status" 502
  expect "no upstream request" is "$(stub_count)" 0
}

case_assets() {
  req GET /
  expect "/ 200 from assets" is "$status" 200
  expect "/ is the home page" cmp -s "$tmp/body" "$assets/index.html"
  req GET /subscribed/
  expect "/subscribed/ 200" is "$status" 200
  expect "/subscribed/ is the confirmation page" cmp -s "$tmp/body" "$assets/subscribed/index.html"
  req GET /about
  expect "/about redirects to /about/" is "$status $(header Location)" "307 /about/"
  req GET /no-such-page/
  expect "unknown path 404" is "$status" 404
  expect "unknown path serves 404.html" cmp -s "$tmp/body" "$assets/404.html"
  req POST /no-such-page/ --data x=1
  expect "POST elsewhere never reaches the signup handler" hasnt "$body" '"ok"'
  expect "no upstream request" is "$(stub_count)" 0
}

run_case "form post -> 303 Location /subscribed/, upstream gets email, Token key, source tag" case_form_303
run_case "scripted post -> 200 {\"ok\":true}" case_json_200
run_case "invalid email -> 400 (JSON and form), no upstream call" case_bad_email_400
run_case "honeypot filled -> success, no upstream call" case_honeypot
run_case "rate limit trips after 5 from one IP, other IP unaffected" case_rate_limit
run_case "upstream 5xx -> 502 friendly message, key never in response" case_upstream_5xx
run_case "upstream unreachable -> 502" case_upstream_unreachable
run_case "already subscribed -> same success" case_already_subscribed
run_case "Buttondown rejects email -> 400" case_upstream_rejects_email
run_case "GET -> 405 Allow: POST" case_get_405
run_case "missing BUTTONDOWN_API_KEY -> 502, no upstream call" case_missing_key
run_case "non-signup paths served from assets (200, 307, 404 page)" case_assets

case_errors=()
expect "key absent from every response" hasnt "$(cat "$tmp/all-responses")" "$key"
if ((${#case_errors[@]} == 0)); then
  printf 'PASS  %s\n' "key never appears in any response (all requests above)"; passed=$((passed + 1))
else
  printf 'FAIL  %s\n' "key never appears in any response (all requests above)"; failed=$((failed + 1))
fi

echo "stub Buttondown received (form-post case): $(cat "$tmp/first-upstream" 2>/dev/null)"
echo "$passed passed, $failed failed"
exit "$failed"
