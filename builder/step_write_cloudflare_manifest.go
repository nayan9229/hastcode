package builder

import (
	"path/filepath"

	"hastcode.com/site/internal/cloudflare"
	"hastcode.com/site/subscribe"
)

func init() {
	registerStep(phaseWrite, 105, "write Cloudflare manifest", writeCloudflareManifest)
}

// Production Target (ADR-0004): Workers Static Assets serving the static
// tree, with the signup Worker (ticket 06) as the only code that runs.
const (
	workerName = "hastcode"
	// workerModule is the Worker's entry point, relative to
	// Config.ToolsDir (the project root holding package.json, where
	// Wrangler is installed).
	workerModule = "worker/index.js"
	// workerCompatibilityDate pins the Workers runtime behaviour. Move it
	// forward deliberately, never to a date later than the pinned
	// Wrangler's runtime supports.
	workerCompatibilityDate = "2026-10-01"
)

// writeCloudflareManifest writes <out>/wrangler.json and the assets
// directory's _headers and _redirects. The deploy adapter (internal/deploy)
// keeps these out of the Vercel upload.
func writeCloudflareManifest(s *site) error {
	main, err := workerMainPath(s.out.Dir, s.cfg.ToolsDir)
	if err != nil {
		return err
	}
	if err := s.out.WriteStatic("/"+cloudflare.HeadersFile, []byte(cloudflareHeaders())); err != nil {
		return err
	}
	if err := s.out.WriteStatic("/"+cloudflare.RedirectsFile, []byte(cloudflareRedirects())); err != nil {
		return err
	}
	return cloudflare.WriteConfig(s.out.Dir, cloudflare.Config{
		Name:              workerName,
		Main:              main,
		CompatibilityDate: workerCompatibilityDate,
		WorkersDev:        true,
		PreviewURLs:       true,
		Assets: cloudflare.Assets{
			Directory: "static",
			Binding:   "ASSETS",
			// Every page is dir/index.html served at /dir/; force keeps a
			// stray file.html from ever answering at a slash-less URL.
			// Workers redirects /dir and /dir/index.html with 307.
			HTMLHandling: "force-trailing-slash",
			// Unknown paths, the retired community sections included
			// (ADR-0001 as amended), get /404.html with status 404.
			NotFoundHandling: "404-page",
			RunWorkerFirst:   []string{subscribe.Path},
		},
	})
}

// cloudflareHeaders is static/_headers, the Production Target's cache
// policy (the Vercel routes' "Cache-Control" rules, same values). Workers
// joins a header set by two matching rules with ", ", so no path may match
// both cache rules: pages end in "/" or ".html", hashed assets do neither.
// Paths no rule matches (feeds, /mark.svg, /pagefind/) keep Workers'
// default, "public, max-age=0, must-revalidate". Headers here never apply
// to the Worker's own responses (the signup path).
func cloudflareHeaders() string {
	return "# Generated by the builder: Cloudflare Workers Static Assets headers.\n" +
		"# Content-hashed files only under " + assetsDir + ".\n" +
		assetsDir + "*\n  Cache-Control: " + immutableCacheControl + "\n\n" +
		"# HTML: browsers revalidate every time.\n" +
		"/\n  Cache-Control: " + htmlCacheControl + "\n" +
		"/*/\n  Cache-Control: " + htmlCacheControl + "\n" +
		"/*.html\n  Cache-Control: " + htmlCacheControl + "\n\n" +
		"# <worker>.<account>.workers.dev and preview URLs\n" +
		"# (<preview>-<worker>.<account>.workers.dev) duplicate the site: keep\n" +
		"# them out of search. hastcode.com is not matched.\n" +
		"https://:worker.:account.workers.dev/*\n  X-Robots-Tag: noindex\n"
}

// cloudflareRedirects is static/_redirects: only the old app's home alias
// (ADR-0001), in both spellings as on Vercel. Workers applies redirects
// before matching assets. The retired community sections deliberately get
// no rule: on the Production Target they are plain 404s (ADR-0001 as
// amended by ADR-0004), via not_found_handling.
func cloudflareRedirects() string {
	return "# Generated by the builder: Cloudflare Workers Static Assets redirects.\n" +
		homeAliasURL + " " + homeURL + " 301\n" +
		homeAliasURL + "/ " + homeURL + " 301\n"
}

// workerMainPath is the Worker module's path relative to the output
// directory, where wrangler.json lives (Wrangler resolves main against it).
func workerMainPath(outDir, toolsDir string) (string, error) {
	out, err := filepath.Abs(outDir)
	if err != nil {
		return "", err
	}
	mod, err := filepath.Abs(filepath.Join(toolsDir, filepath.FromSlash(workerModule)))
	if err != nil {
		return "", err
	}
	rel, err := filepath.Rel(out, mod)
	if err != nil {
		return "", err
	}
	return filepath.ToSlash(rel), nil
}
